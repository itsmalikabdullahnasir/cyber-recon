"""Read-only VM operational diagnostics. Never includes environment secrets."""

import io
import json
import os
import shutil
import subprocess
import time
import zipfile
from datetime import datetime, timezone
from pathlib import Path

from . import cve_db
from .config import get_settings
from .jobs import pending_count


TOOLS = ("subfinder_bin", "dnsx_bin", "httpx_bin", "nuclei_bin", "nmap_bin", "feroxbuster_bin", "whatweb_bin", "wafw00f_bin", "nikto_bin", "testssl_bin", "chromium_bin")


def _command(args: list[str]) -> str | None:
    try:
        output = subprocess.run(args, stdin=subprocess.DEVNULL, capture_output=True, text=True, timeout=4, check=False).stdout
        return output.strip().splitlines()[0][:200] if output.strip() else None
    except (OSError, subprocess.SubprocessError):
        return None


def _service_time() -> str | None:
    # cve-sync is a local systemd unit. A missing systemd just reports null.
    value = _command(["systemctl", "show", "cve-sync.service", "--property=ExecMainExitTimestamp", "--value"])
    return value if value and value != "n/a" else None


def snapshot() -> dict:
    s = get_settings()
    disk = shutil.disk_usage(s.results_dir)
    mem = {}
    try:
        for line in Path("/proc/meminfo").read_text().splitlines():
            key, value = line.split(":", 1)
            mem[key] = int(value.strip().split()[0]) * 1024
    except (OSError, ValueError):
        pass
    tools = []
    for attribute in TOOLS:
        path = str(getattr(s, attribute))
        installed = os.access(path, os.X_OK)
        tools.append({"name": attribute.removesuffix("_bin"), "path": path, "installed": installed,
                      "version": _command([path, "--version"]) if installed else None})
    cve = {"ready": False, "last_sync": None, "age_hours": None}
    try:
        with cve_db.connect(readonly=True) as conn:
            row = conn.execute("select v from meta where k = 'last_sync'").fetchone()
            cve["ready"] = cve_db.is_ready(s.cve_db_path)
            cve["last_sync"] = row["v"] if row else None
            if row:
                cve["age_hours"] = round((datetime.now(timezone.utc) - datetime.fromisoformat(row["v"])).total_seconds() / 3600, 1)
    except Exception:
        pass
    return {
        "generated_at": datetime.now(timezone.utc).isoformat(), "uptime_seconds": round(time.time() - os.stat("/proc/1").st_ctime) if os.path.exists("/proc/1") else None,
        "cpu": {"cores": os.cpu_count(), "load_1m": os.getloadavg()[0] if hasattr(os, "getloadavg") else None},
        "memory": {"total_bytes": mem.get("MemTotal"), "available_bytes": mem.get("MemAvailable")},
        "disk": {"total_bytes": disk.total, "used_bytes": disk.used, "free_bytes": disk.free},
        "queue_depth": pending_count(), "cve_database": cve, "last_successful_scheduled_job": _service_time(), "tools": tools,
    }


def bundle() -> bytes:
    """A portable, secret-free support bundle generated in memory."""
    payload = snapshot()
    stream = io.BytesIO()
    with zipfile.ZipFile(stream, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("worker-diagnostics.json", json.dumps(payload, indent=2, sort_keys=True))
        archive.writestr("README.txt", "Generated by Cyber Recon. This bundle excludes environment variables, secrets, scan outputs, and screenshots.\n")
    return stream.getvalue()
